/** Troca {o}/{a}/{ele} pelo género do NPC: "cansad{o}" → cansado/cansada,
 * "protetor{a}" → protetor/protetora. */
export function comGenero(texto, genero) {
  const f = genero === 'f';
  return String(texto || '')
    .replace(/\{o\}/g, f ? 'a' : 'o')
    .replace(/\{a\}/g, f ? 'a' : '')
    .replace(/\{ele\}/g, f ? 'ela' : 'ele')
    .replace(/\{Ele\}/g, f ? 'Ela' : 'Ele');
}
