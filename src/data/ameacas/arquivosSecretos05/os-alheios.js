//
// Sobre o descritor "Transmissão": o livro explica isto explicitamente (p.46,
// caixa "CRIATURAS DE TRANSMISSÃO"): "A existência dos Sinos de Tenebris interfere
// no comportamento dos elementos, conectando-os de formas misteriosas. A Transmissão
// é um resultado dessa conexão complexa, unindo Conhecimento e Energia em uma
// manifestação única. As criaturas de Transmissão, em termos de jogo, pertencem a
// esses dois elementos ao mesmo tempo." Ou seja, "Transmissão" não é invenção nossa
// nem um erro por "Conhecimento e Energia" — é o próprio termo de jogo que o livro
// usa no cabeçalho da ficha de cada um dos 9 Alheios abaixo, e foi transcrito
// literalmente como descritor (`descritores: ['Transmissão']`), com esta nota a
// registar que mecanicamente equivale a Conhecimento + Energia simultâneos.
//
// Sobre a Força "-" de Memoflígico: o livro imprime "FOR -" (sem valor numérico)
// para esta criatura incorpórea, mesma situação do Simulacro.EXE em Arquivos
// Secretos 04 — deixado como `null` em vez de inventado.
//
// Sobre o Hospedeiro Parasitado (p.36-37): é a ficha "PESSOA" de uma vítima humana
// ainda viva, mas controlada por dentro por um interflorado. O livro dá 4 variações
// opcionais de "reskin" para o mestre usar (Acólito, Faz-Tudo, Guerrilheiro,
// Socorrista) — cada uma só altera atributos/perícias/uma habilidade pontual da
// ficha base, sem fornecer um stat block completo à parte. Por isso, as 4 ficaram
// como texto dentro de UMA habilidade "Variação de Hospedeiros" na ficha do
// Hospedeiro Parasitado, em vez de 4 entradas extra inventadas com dados que o
// livro não fornece por completo.
//
// Todas as fichas "CRIATURA" desta seção (os 9 Alheios) são type "Ameaça
// Paranormal" com Presença Perturbadora, tal como as criaturas paranormais do
// Livro Base/Sobrevivendo ao Horror — ao contrário dos Transtornados/Mascarados
